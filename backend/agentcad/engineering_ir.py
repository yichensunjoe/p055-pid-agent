def _neighbours(
    edges: list[TopologyEdge],
    node: str,
) -> list[tuple[str, str, Literal["upstream", "downstream", "undirected"]]]:
    """Return (neighbour, connector_id, direction) sorted for determinism."""

    out: list[tuple[str, str, Literal["upstream", "downstream", "undirected"]]] = []
    for edge in edges:
        if edge.source_object_id == node and edge.target_object_id:
            out.append(
                (
                    edge.target_object_id,
                    edge.connector_id,
                    "downstream" if edge.directed else "undirected",
                )
            )
        if edge.target_object_id == node and edge.source_object_id:
            out.append(
                (
                    edge.source_object_id,
                    edge.connector_id,
                    "upstream" if edge.directed else "undirected",
                )
            )
    return sorted(out, key=lambda item: (item[0], item[1]))


def _node_neighbours(
    graph: EngineeringGraph,
    node: str,
) -> list[tuple[str, str, Literal["upstream", "downstream", "undirected"]]]:
    """Expand one node, including the "start from a pipeline" case.

    For a pipeline node the members are the connectors sharing that tag: their
    endpoints are reported with the pipeline's own reading direction (declared
    source is upstream, declared target is downstream; undeclared flow is
    undirected), which is the only interpretation the drawing actually supports.
    """

    member_edges = [edge for edge in graph.edges if edge.pipeline_object_id == node]
    if not member_edges:
        return _neighbours(graph.edges, node)
    out: list[tuple[str, str, Literal["upstream", "downstream", "undirected"]]] = []
    for edge in member_edges:
        for endpoint_id, edge_direction in (
            (edge.source_object_id, "upstream"),
            (edge.target_object_id, "downstream"),
        ):
            if not endpoint_id or endpoint_id.startswith("unbound:"):
                continue
            out.append(
                (endpoint_id, edge.connector_id, edge_direction if edge.directed else "undirected")
            )
    return sorted(out, key=lambda item: (item[0], item[1]))


def trace_engineering_object(
    graph: EngineeringGraph,
    object_id: str,
    *,
    direction: TraceDirection = "both",
    max_depth: int = 64,
    max_steps: int = 512,
) -> TraceResult:
    """Walk the graph from one engineering object.

    Direction is honoured only for edges that declare a flow direction; undeclared
    (``none``) connections are traversable both ways, which matches how a P&ID is
    actually read (topology first, flow second).
    """

    if graph.object(object_id) is None:
        raise KeyError(f"unknown engineering object: {object_id}")
    allowed: set[str]
    if direction == "both":
        allowed = {"upstream", "downstream", "undirected"}
    elif direction == "downstream":
        allowed = {"downstream", "undirected"}
    else:
        allowed = {"upstream", "undirected"}

    steps: list[TraceStep] = [
        TraceStep(
            depth=0,
            object_id=object_id,
            kind=graph.object(object_id).kind,  # type: ignore[union-attr]
            direction="origin",
        )
    ]
    visited = {object_id}
    queue: deque[tuple[str, int]] = deque([(object_id, 0)])
    truncated = False
    while queue:
        node, depth = queue.popleft()
        if depth >= max_depth:
            truncated = True
            continue
        for neighbour, connector_id, edge_direction in _node_neighbours(graph, node):
            if edge_direction not in allowed:
                continue
            if neighbour in visited or neighbour.startswith("unbound:"):
                continue
            if len(steps) >= max_steps:
                truncated = True
                break
            visited.add(neighbour)
            record = graph.object(neighbour)
            steps.append(
                TraceStep(
                    depth=depth + 1,
                    object_id=neighbour,
                    kind=record.kind if record else "graphic",
                    via_connector_id=connector_id,
                    direction=edge_direction,
                )
            )
            queue.append((neighbour, depth + 1))
    traversed = {
        edge.pipeline_object_id
        for edge in graph.edges
        if edge.connector_id in {step.via_connector_id for step in steps if step.via_connector_id}
        and edge.pipeline_object_id
    }
    return TraceResult(
        document_id=graph.document_id,
        revision=graph.revision,
        origin_object_id=object_id,
        direction=direction,
        steps=steps,
        reached_object_ids=sorted(visited),
        traversed_pipeline_ids=sorted(traversed),
        truncated=truncated,
    )


