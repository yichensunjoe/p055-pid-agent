def _slug(value: str) -> str:
    cleaned = " ".join(value.strip().split()).casefold()
    out = [char if (char.isalnum() or char in "-_.") else "-" for char in cleaned]
    slug = "".join(out).strip("-")
    return slug or "unnamed"


_KIND_PREFIX: dict[str, str] = {
    "equipment": "equipment",
    "valve": "valve",
    "instrument": "instrument",
    "line": "line",
    "junction": "junction",
    "off_page_connector": "opc",
    "annotation": "annotation",
    "graphic": "graphic",
}


def _identity(
    kind: ObjectKind,
    tag: str,
    fallback: str,
    used: Counter[str],
) -> tuple[str, IdentityScope, str]:
    """Return (object_id, identity_scope, base_identity).

    The base identity is what an engineer would call the object (``valve:hv-101``).
    Collisions inside one document get a deterministic ``#n`` suffix ordered by
    element id, because two valves really can carry the same tag on a bad drawing and
    silently merging them would be an engineering lie.
    """

    if tag.strip():
        base = f"{_KIND_PREFIX[kind]}:{_slug(tag)}"
        scope: IdentityScope = "tag"
    else:
        base = f"{_KIND_PREFIX[kind]}:{fallback}"
        scope = "element"
    used[base] += 1
    if used[base] == 1:
        return base, scope, base
    return f"{base}#{used[base]}", scope, base


