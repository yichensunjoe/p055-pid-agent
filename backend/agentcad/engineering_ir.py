"""Derived engineering IR: the semantic graph behind a P&ID document.

Charter reference: §6 (semantic first), §8 (engineering objects, not pixels), §16
(M2 engineering semantic graph). The drawing document stores *geometry*; this module
derives the *engineering objects* an engineer actually reasons about:

    equipment · valve · instrument · line (pipeline) · junction · off_page_connector
    annotation · graphic

Design rules
------------
* **Derived, never authoritative.** The graph is a pure function of
  ``(document, symbol registry)``. Nothing here writes the document, so it cannot
  become a second source of truth. ``document_content_hash`` makes that function
  checkable, which is what lets the project index detect staleness.
* **Stable identity.** An object id is derived from its engineering tag
  (``valve:HV-101``) whenever the tag exists, so the same valve keeps the same
  identity across revisions even though its element id is regenerated by imports.
  Duplicate tags are disambiguated deterministically (``#2`` ordered by element id)
  and raise a finding instead of silently merging two real objects.
  ``identity_scope`` states honestly which basis was used: ``tag`` or ``element``.
* **Pixels never become engineering truth.** Coordinates, styles and SVG output are
  intentionally absent from the graph; geometry is only used for connectivity
  (ports, endpoints) and length.
* Signal/process classification is explicit-medium-driven, with one conservative
  structural rule (instrument-to-instrument). A process tap on a line is *not*
  reclassified as a signal.
"""

from __future__ import annotations

import hashlib
import json
from collections import Counter, defaultdict, deque
from math import hypot
from typing import Any, Literal

from pydantic import Field

from .flow_topology import is_opc_symbol, is_valve_symbol, normalize_flow_medium, opc_direction
from .models import Document, Element, StrictModel
from .symbols import SymbolRegistry

IR_SCHEMA = "pid-agent.engineering-graph"
IR_VERSION = 1
IR_BUILDER_VERSION = 1

ObjectKind = Literal[
    "equipment",
    "valve",
    "instrument",
    "line",
    "junction",
    "off_page_connector",
    "annotation",
    "graphic",
]
IdentityScope = Literal["tag", "element"]
FindingSeverity = Literal["info", "warning", "error"]
TraceDirection = Literal["upstream", "downstream", "both"]

#: Object kinds that participate in process topology (annotations/graphics do not).
TOPO_KINDS: frozenset[str] = frozenset(
    {"equipment", "valve", "instrument", "line", "junction", "off_page_connector"}
)

#: Mediums that mean "this connector carries an instrument signal, not process fluid".
_SIGNAL_TOKENS: tuple[str, ...] = (
    "signal",
    "signal_line",
    "electric",
    "electrical",
    "elec",
    "instrument",
    "instrumentation",
    "impulse",
    "pneumatic",
    "data",
    "communication",
    "信号",
    "电信号",
    "电气",
    "电",
    "气动",
    "脉冲",
    "通讯",
    "通信",
)


class EngineeringObject(StrictModel):
    """One engineering entity derived from one or more drawing elements."""

    object_id: str = Field(min_length=1)
    kind: ObjectKind
    identity_scope: IdentityScope
    tag: str = ""
    name: str = ""
    label: str = ""
    symbol_key: str = ""
    symbol_name: str = ""
    category: str = ""
    capability: str = ""
    element_ids: list[str] = Field(default_factory=list)
    primary_element_id: str
    layer_id: str = ""
    layer_name: str = ""
    system_id: str = ""
    system_name: str = ""
    media: str = ""
    medium_class: str = ""
    nominal_diameter: str = ""
    flow_direction: str = "none"
    required_port_count: int = 0
    connected_port_count: int = 0
    connection_count: int = 0
    length: float = 0.0
    opc_direction: Literal["in", "out", ""] = ""
    target_document_id: str = ""
    properties: dict[str, Any] = Field(default_factory=dict)


class TopologyEdge(StrictModel):
    """A directed (or undirected, when flow is undeclared) connection between objects."""

    connector_id: str
    pipeline_object_id: str
    source_object_id: str
    target_object_id: str
    source_port_id: str = ""
    target_port_id: str = ""
    medium: str = ""
    medium_class: str = ""
    flow_direction: Literal["forward", "reverse", "none"] = "none"
    directed: bool = False


class SignalLink(StrictModel):
    connector_id: str
    source_object_id: str = ""
    target_object_id: str = ""
    medium: str = ""
    instrument_object_ids: list[str] = Field(default_factory=list)
    classification: Literal["declared_medium", "instrument_to_instrument"] = "declared_medium"


class GraphFinding(StrictModel):
    severity: FindingSeverity
    code: str
    message: str
    object_ids: list[str] = Field(default_factory=list)
    element_ids: list[str] = Field(default_factory=list)
    details: dict[str, Any] = Field(default_factory=dict)


class EngineeringGraphCounts(StrictModel):
    equipment: int = 0
    valves: int = 0
    instruments: int = 0
    lines: int = 0
    junctions: int = 0
    off_page_connectors: int = 0
    annotations: int = 0
    graphics: int = 0
    objects: int = 0
    edges: int = 0
    signal_links: int = 0
    errors: int = 0
    warnings: int = 0
    info: int = 0


class EngineeringGraph(StrictModel):
    schema_name: Literal["pid-agent.engineering-graph"] = Field(
        default=IR_SCHEMA, alias="schema"
    )
    version: Literal[1] = IR_VERSION
    builder_version: Literal[1] = IR_BUILDER_VERSION
    document_id: str
    document_name: str
    revision: int
    content_hash: str
    counts: EngineeringGraphCounts
    objects: list[EngineeringObject]
    edges: list[TopologyEdge]
    signal_links: list[SignalLink]
    off_page_object_ids: list[str]
    connectivity_components: list[list[str]]
    findings: list[GraphFinding]

    def object(self, object_id: str) -> EngineeringObject | None:
        for item in self.objects:
            if item.object_id == object_id:
                return item
        return None


class TraceStep(StrictModel):
    depth: int
    object_id: str
    kind: ObjectKind
    via_connector_id: str = ""
    direction: Literal["upstream", "downstream", "undirected", "origin"] = "undirected"


class TraceResult(StrictModel):
    """Result of walking the graph.

    Steps are *engineering objects*. Pipelines are deliberately not steps: a pipeline
    aggregates every connector that shares a tag, so it is not a single node on a
    path. The pipelines actually traversed are reported separately, and a trace may
    also be *started* from a pipeline object to enumerate what it connects.
    """

    document_id: str
    revision: int
    origin_object_id: str
    direction: TraceDirection
    steps: list[TraceStep]
    reached_object_ids: list[str]
    traversed_pipeline_ids: list[str] = Field(default_factory=list)
    truncated: bool = False


